// playwright-cli -s=p0 run-code --filename=scripts/check-discovery-browser.js
async (page) => {
  const base = await page.evaluate(() => `${location.origin}${location.pathname}`);
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light" });
  const target = await context.newPage();
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const ready = () => target.waitForFunction(() => document.querySelector("#directory-results")?.getAttribute("aria-busy") === "false");
  const errors = [];
  const requests = [];
  target.on("pageerror", (error) => errors.push(error.message));
  target.on("request", (request) => requests.push(request.url()));
  await target.goto(base);
  await ready();
  assert(await target.locator(".part-excerpt").count() === 0, "Directory still shows automatic excerpts");
  const sourceLink = target.locator(".video-meta a").first();
  const bvid = await sourceLink.textContent();
  assert((await sourceLink.getAttribute("href")).includes(`/video/${bvid}/`), "BV link has wrong source");
  assert(await sourceLink.getAttribute("target") === "_blank" && (await sourceLink.getAttribute("rel")).includes("noopener"), "Source link lacks safe new-tab attributes");
  while (!await target.locator('.video-heading h2 a[href*="BV1dA411T7xD"]').count()) {
    const before = await target.locator(".video-group").count();
    await target.getByRole("button", { name: /再显示/ }).click();
    await target.waitForFunction((before) => document.querySelectorAll(".video-group").length > before, before);
  }
  await target.locator('.video-heading h2 a[href*="BV1dA411T7xD"]').click();
  await ready();
  assert(await target.locator(".video-part").count() === 13, "Video overview did not collect all parts");
  assert(await target.locator(".part-excerpt").count() === 0, "Overview still shows automatic excerpts");
  assert(await target.locator(".part-number").allTextContents().then((parts) => parts.join(",")) === Array.from({ length: 13 }, (_, i) => `P${i + 1}`).join(","), "Numeric part order wrong");
  assert(await target.locator(".part-link").first().boundingBox().then((box) => box.y < 900), "Overview puts first part below desktop viewport");
  assert(!requests.some((url) => /\.md$|search-.*\.json/.test(url)), "Overview eagerly loaded content");
  await target.screenshot({ path: "artifacts/discovery-video-desktop.png", animations: "disabled", fullPage: false });
  await target.getByRole("radio", { name: "正文关键词" }).check();
  await target.getByRole("searchbox", { name: "在此视频中查找" }).fill("审美 痛苦");
  await target.waitForFunction(() => document.querySelector(".match-summary")?.textContent?.includes("全部关键词命中"));
  await ready();
  assert(await target.locator(".passage-link mark").count() > 1, "Keyword evidence absent");
  const scope = await target.evaluate(() => new URL(location.href).searchParams.get("video"));
  const shared = target.url();
  const parts = await target.locator(".part-number").allTextContents();
  const disclosure = target.locator(".passage-disclosure").first();
  assert(await disclosure.count() > 0, "Multi-passage disclosure missing");
  await disclosure.locator("summary").click();
  const edition = await disclosure.getAttribute("data-entry");
  await disclosure.locator(".passage-link").first().click();
  await target.locator(".search-passage mark").first().waitFor();
  assert(await target.locator(".search-arrival").textContent().then((text) => /审美|痛苦/.test(text)), "Passage query lost");
  await target.getByRole("link", { name: "校验参照稿件", exact: true }).click();
  await target.locator(".review-reference-notice").waitFor();
  await target.getByRole("link", { name: "视频总览 · 全部分 P →" }).click();
  await ready();
  assert(await target.evaluate(() => new URL(location.href).searchParams.get("video")) === scope, "Return lost video scope");
  assert(await target.locator("#search").inputValue() === "审美 痛苦", "Return lost query");
  assert(await target.getByRole("radio", { name: "正文关键词" }).isChecked(), "Return lost mode");
  assert(await target.locator(`.passage-disclosure[data-entry="${edition}"]`).getAttribute("open") !== null, "Passage expansion lost");
  const fresh = await context.newPage();
  await fresh.goto(shared);
  await fresh.waitForFunction(() => document.querySelector("#directory-results")?.getAttribute("aria-busy") === "false");
  assert(await fresh.locator(".part-number").allTextContents().then((items) => items.join(",")) === parts.join(","), "Share URL changed matches");
  await fresh.close();
  await target.getByRole("navigation", { name: "视频稿件类别" }).getByRole("link", { name: "已发布 0", exact: true }).click();
  await ready();
  assert(await target.locator("#search").inputValue() === "审美 痛苦", "Category switch discarded query");
  await target.getByRole("button", { name: "清空搜索" }).click();
  await ready();
  await target.getByRole("heading", { name: "此类别暂无收录稿件" }).waitFor();
  await target.goBack();
  await ready();
  assert(await target.locator("#search").inputValue() === "审美 痛苦", "History lost query");
  await target.getByRole("radio", { name: "正文原句" }).check();
  await target.locator("#search").fill("这句原话一定不会出现在正文中xyz987");
  await target.getByRole("heading", { name: "本视频没有匹配的稿件" }).waitFor();
  await target.locator("#search").fill("审美");
  await target.waitForFunction(() => document.querySelector(".match-summary")?.textContent?.includes("原句匹配"));
  await ready();
  for (const width of [375, 768, 1024, 1440]) {
    await target.setViewportSize({ width, height: 900 });
    assert(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
  }
  await target.setViewportSize({ width: 390, height: 844 });
  await target.screenshot({ path: "artifacts/discovery-search-mobile.png", animations: "disabled" });
  await target.getByRole("button", { name: "切换深浅主题" }).click();
  await target.screenshot({ path: "artifacts/discovery-search-mobile-dark.png", animations: "disabled" });
  await target.goto(`${base}?view=all&mode=keywords&q=${encodeURIComponent("克尔凯郭尔 痛苦")}`);
  await ready();
  assert(await target.locator(".video-group").count() > 0, "Global keyword search empty");
  const input = target.getByRole("searchbox");
  await input.dispatchEvent("compositionstart");
  await input.fill("克尔凯郭尔 审美");
  await input.dispatchEvent("compositionend");
  await target.waitForFunction(() => new URL(location.href).searchParams.get("q") === "克尔凯郭尔 审美" && document.querySelector("#directory-results")?.getAttribute("aria-busy") === "false");
  await target.screenshot({ path: "artifacts/discovery-search-desktop.png", animations: "disabled" });
  await target.goto(`${base}?view=published&tag=${encodeURIComponent("哲学")}&q=`);
  await ready();
  assert(await target.locator(".filter-current").textContent() === "哲学", "Explicit source tag was silently discarded");
  await target.goto(`${base}?video=missing`);
  await target.getByRole("heading", { name: "没有找到这个视频" }).waitFor();
  assert(errors.length === 0, errors.join("; "));
  await context.close();
  return { passed: true, checks: ["overview lazy loading", "P1–P13 order", "keyword evidence", "multiple passages", "reference return", "query/mode/expansion restore", "share URL", "empty category", "history", "phrase/no results", "responsive light/dark", "global query", "IME composition", "no runtime errors"] };
}
