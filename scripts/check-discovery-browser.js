async (page) => {
  const base = await page.evaluate(() => `${location.origin}${location.pathname}`);
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light" });
  const target = await context.newPage();
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const ready = () => target.waitForFunction(() => document.querySelector("#video-results")?.getAttribute("aria-busy") === "false");
  const errors = [];
  target.on("pageerror", (error) => errors.push(error.message));
  try {
    await target.goto(`${base}?video=BV1dA411T7xD&view=all`);
    await target.locator(".reader-video-search").waitFor();
    const navigation = target.getByRole("navigation", { name: "同视频分 P 导航" }).first();
    assert(await navigation.locator("ol a").allTextContents().then((parts) => parts.join(",")) === Array.from({ length: 13 }, (_, i) => `P${i + 1}`).join(","), "Numeric part order wrong");
    await navigation.getByRole("link", { name: "P10", exact: true }).click();
    await target.locator(".reading-meta .current-part").filter({ hasText: "P10" }).waitFor();
    await target.locator(".reader-video-search > summary").click();
    await target.locator("#advanced-search > summary").click();
    await target.getByRole("radio", { name: "正文关键词" }).check();
    await target.locator("#video-query").fill("审美 痛苦");
    await target.waitForFunction(() => document.querySelector(".match-summary")?.textContent?.includes("全部关键词命中"));
    await ready();
    assert(await target.locator("#video-results .passage-link mark").count() > 1, "Keyword evidence absent");
    const shared = target.url();
    const parts = await target.locator("#video-results .part-number").allTextContents();
    const disclosure = target.locator(".passage-disclosure").first();
    await disclosure.locator("summary").click();
    await disclosure.locator(".passage-link").first().click();
    await target.locator(".search-passage mark").first().waitFor();
    await ready();
    assert(await target.locator("#video-query").inputValue() === "审美 痛苦", "Result navigation lost query");
    await target.getByRole("link", { name: "校验参照稿件", exact: true }).click();
    await target.locator(".provenance > summary").click();
    await target.locator(".review-reference-notice").waitFor();
    await ready();
    assert(await target.locator("#video-query").inputValue() === "审美 痛苦", "Reference navigation lost query");
    await target.getByRole("link", { name: "正文", exact: true }).click();
    await target.locator(".reading-article .prose").waitFor();
    await ready();
    const fresh = await context.newPage();
    await fresh.goto(shared);
    await fresh.waitForFunction(() => document.querySelector("#video-results")?.getAttribute("aria-busy") === "false" && document.querySelector(".match-summary"));
    assert(await fresh.locator("#video-results .part-number").allTextContents().then((items) => items.join(",")) === parts.join(","), "Shared query changed matches");
    await fresh.close();
    await target.locator("#video-search-view").selectOption("published");
    await ready();
    assert(await target.locator("#video-query").inputValue() === "审美 痛苦", "Category switch lost query");
    await target.getByRole("button", { name: "清空视频内搜索" }).click();
    await target.getByRole("heading", { name: "此类别暂无收录稿件" }).waitFor();
    await target.locator("#video-search-view").selectOption("drafts");
    await target.getByRole("radio", { name: "正文原句" }).check();
    await target.locator("#video-query").fill("这句原话一定不会出现在正文中xyz987");
    await target.getByRole("heading", { name: "本视频没有匹配的稿件" }).waitFor();
    await target.locator("#video-query").fill("审美");
    await target.waitForFunction(() => document.querySelector(".match-summary")?.textContent?.includes("原句匹配"));
    const input = target.locator("#video-query");
    await input.dispatchEvent("compositionstart");
    await input.fill("痛苦");
    await input.dispatchEvent("compositionend");
    await target.waitForFunction(() => new URL(location.href).searchParams.get("vq") === "痛苦" && document.querySelector("#video-results")?.getAttribute("aria-busy") === "false");
    for (const width of [375, 768, 1024, 1440]) {
      await target.setViewportSize({ width, height: 900 });
      assert(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
    }
    await target.locator(".reader-video-search").scrollIntoViewIfNeeded();
    await target.screenshot({ path: "artifacts/reader-video-search-desktop.png" });
    await target.setViewportSize({ width: 375, height: 900 });
    await target.screenshot({ path: "artifacts/reader-video-search-mobile.png" });
    await target.locator(".reader-site-menu > summary").click();
    await target.getByRole("button", { name: "切换深浅主题" }).click();
    await target.locator(".reader-video-search").scrollIntoViewIfNeeded();
    await target.screenshot({ path: "artifacts/reader-video-search-mobile-dark.png" });
    await target.goto(`${base}?view=all&mode=keywords&q=${encodeURIComponent("克尔凯郭尔 痛苦")}`);
    await target.locator(".video-group").first().waitFor();
    const globalQuery = target.locator("#search");
    await globalQuery.dispatchEvent("compositionstart");
    await globalQuery.fill("克尔凯郭尔 审美");
    await globalQuery.dispatchEvent("compositionend");
    await target.waitForFunction(() => new URL(location.href).searchParams.get("q") === "克尔凯郭尔 审美" && document.querySelector("#directory-results")?.getAttribute("aria-busy") === "false");
    await target.goto(`${base}?video=missing`);
    await target.getByRole("heading", { name: "没有找到这个视频" }).waitFor();
    assert(errors.length === 0, errors.join("; "));
    return { passed: true, checks: ["P1-P13 order", "P10 switch", "keyword evidence", "multiple passages", "reference query", "share URL", "empty category", "phrase/no results", "responsive themes", "global query", "IME composition"] };
  } finally { await context.close(); }
}
