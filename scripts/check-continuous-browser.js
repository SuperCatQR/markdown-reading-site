// playwright-cli -s=p0 run-code --filename=scripts/check-continuous-browser.js
async (page) => {
  const base = await page.evaluate(() => `${location.origin}${location.pathname}`);
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 900 } });
  const target = await context.newPage();
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const requests = [];
  const errors = [];
  target.on("request", (request) => requests.push(request.url()));
  target.on("pageerror", (error) => errors.push(error.message));
  const ready = () => target.waitForFunction(() => !!document.querySelector(".continuous-part") && !document.querySelector("#retry-document") && document.querySelector(".continuous-feedback")?.getAttribute("aria-busy") !== "true" && (!new URL(location.href).searchParams.has("part") || history.state?.continuous?.current === new URL(location.href).searchParams.get("part")));
  try {
    await target.goto(`${base}?platform=bilibili&video=BV1dA411T7xD&view=all`);
    await target.locator(".reading-parts > summary").click();
    await target.locator(".parts-navigation").first().getByRole("link", { name: "从此 P 连续阅读 →" }).click();
    await ready();
    assert(await target.locator(".continuous-part").count() === 1, "Initial stream loaded multiple parts");
    assert(requests.filter((url) => /\.md$/.test(url)).length === 1, "Initial stream fetched more than one body");
    assert(!requests.some((url) => /search-.*\.json|\/review-.*\.md/.test(url)), "Stream eagerly fetched index or reference");
    const firstId = await target.locator(".continuous-part").getAttribute("data-edition");
    await target.evaluate(() => scrollTo(0, 1000));
    await target.waitForFunction(() => history.state?.continuous?.scroll >= 990);
    const savedScroll = await target.evaluate(() => scrollY);
    await target.getByRole("link", { name: /加载下一部分 · P2/ }).evaluate((link) => link.click());
    await ready();
    assert(await target.locator(".continuous-part").count() === 2, "Previous body was lost on append");
    assert(requests.filter((url) => /\.md$/.test(url)).length === 2, `Next part did not load individually: ${requests.join(",")}`);
    const secondId = await target.locator(".continuous-part").last().getAttribute("data-edition");
    assert(await target.evaluate(() => new URL(location.href).searchParams.get("part")) === secondId, "URL lost exact edition");
    assert(await target.evaluate(() => { const ids = [...document.querySelectorAll("[id]")].map((node) => node.id); return new Set(ids).size === ids.length; }), "Duplicate stream anchors");
    await target.goBack();
    await ready();
    assert(await target.locator(".continuous-part").count() === 1, "Back lost original loaded set");
    assert(Math.abs(await target.evaluate(() => scrollY) - savedScroll) < 5, "Back lost stream position");
    await target.goForward();
    await ready();
    assert(await target.locator(".continuous-part").count() === 2, "Forward lost appended parts");
    assert(requests.filter((url) => /\.md$/.test(url)).length === 2, "History refetched cached bodies");
    await target.locator(".continuous-part").last().getByRole("link", { name: "单篇正文", exact: true }).click();
    await target.locator(".reading-article .prose").waitFor();
    await target.getByRole("link", { name: "校验参照稿件", exact: true }).click();
    await target.locator(".provenance > summary").click();
    await target.locator(".review-reference-notice").waitFor();
    await target.getByRole("link", { name: "返回连续阅读 →" }).click();
    await ready();
    assert(await target.locator(".continuous-part").count() === 2, "Reference return lost stream");
    await target.getByRole("navigation", { name: "连续阅读分 P 目录" }).getByRole("link", { name: "P10", exact: true }).click();
    await ready();
    assert(await target.locator(".continuous-part").count() === 3, "Jump fetched intervening parts");
    assert(await target.locator(".continuous-part > .reading-heading .current-part").allTextContents().then((parts) => parts.join(",")) === "P1,P2,P10", "Jumped body order wrong");
    await target.getByRole("navigation", { name: "连续阅读分 P 目录" }).getByRole("link", { name: "P13", exact: true }).click();
    await ready();
    assert(await target.locator(".continuous-feedback").textContent().then((text) => text.includes("最后一个")), "Last part has wrong next action");
    const shared = target.url();
    const fresh = await context.newPage();
    await fresh.goto(shared);
    await fresh.locator(".continuous-part").waitFor();
    assert(await fresh.locator(".continuous-part").count() === 1, "New shared URL loaded earlier bodies");
    assert(await fresh.locator(".continuous-part > .reading-heading .current-part").textContent() === "P13", "Share opened wrong part");
    await fresh.close();
    await target.reload();
    await ready();
    assert(await target.locator(".continuous-part").count() === 1, "Reload eagerly restored all former bodies");
    for (const width of [375, 768, 1440]) {
      await target.setViewportSize({ width, height: 900 });
      assert(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
      assert(await target.locator(".continuous-directory a").first().boundingBox().then((box) => box.height >= 44 && box.width >= 44), "Part targets too small");
    }
    await target.screenshot({ path: "artifacts/continuous-desktop-light.png", fullPage: false });
    await target.setViewportSize({ width: 375, height: 900 });
    await target.evaluate(() => scrollTo(0, 0));
    await target.screenshot({ path: "artifacts/continuous-mobile-light.png", fullPage: false });
    await target.locator(".reader-site-menu > summary").click();
    await target.getByRole("button", { name: "切换深浅主题" }).click();
    await target.screenshot({ path: "artifacts/continuous-mobile-dark.png", fullPage: false });
    await target.goto(`${base}?platform=bilibili&video=BV1dA411T7xD&view=published&flow=continuous`);
    await target.getByText("此类别暂无收录稿件，可返回单篇阅读切换查找类别。").waitFor();
    assert(await target.locator(".continuous-part").count() === 0, "Empty release flow mixed in drafts");
    await target.goto(`${base}?platform=bilibili&video=BV1dA411T7xD&view=drafts&flow=continuous&part=${firstId}#%ZZ`);
    await ready();
    await target.route(/\.md$/, (route) => route.fulfill({ status: 503, body: "unavailable" }));
    await target.getByRole("link", { name: /加载下一部分 · P2/ }).click();
    await target.getByRole("alert").getByText(/加载失败/).waitFor();
    assert(await target.locator(".continuous-part").count() === 1, "Failed request removed existing body");
    await target.unroute(/\.md$/);
    await target.getByRole("button", { name: "重新加载", exact: true }).click();
    await ready();
    assert(await target.locator(".continuous-part").count() === 2, "Retry did not retain first body");
    await target.reload();
    await ready();
    let release;
    const hold = new Promise((resolve) => { release = resolve; });
    await target.route(/\.md$/, async (route) => { await hold; await route.continue(); });
    await target.getByRole("link", { name: /加载下一部分 · P3/ }).click();
    await target.getByText("正在加载 P3 正文…").waitFor();
    await target.locator(".continuous-shell > .back-link").evaluate((link) => link.click());
    await target.locator(".reading-article .prose").waitFor();
    release();
    await target.waitForLoadState("networkidle");
    assert(await target.locator(".continuous-part").count() === 0, "Late body replaced destination page");
    assert(errors.length === 0, errors.join("\n"));
    return { status: "passed", initialBodyRequests: 1, historyRestored: true, exactShare: true, categoryIsolation: true, widths: [375, 768, 1440] };
  } finally { await context.close(); }
}
